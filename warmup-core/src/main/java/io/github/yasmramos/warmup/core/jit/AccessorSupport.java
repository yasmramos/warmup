package io.github.yasmramos.warmup.core.jit;

import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;

/**
 * Reflection bridge used only by generated accessor classes.
 *
 * <p>The JVM forbids one generated class from writing another class's private
 * fields or invoking its private methods, even when both live in the same
 * package. To support {@code @Inject}/{@code @Value} on non-public members the
 * annotation processor emits a small {@code Bean$$WarmupAccessor} per bean that
 * holds the reflected {@link Field}/{@link Method} and forwards here. Keeping
 * the reflective calls in this one class means the generated bytecode stays
 * free of exception-handling frames, and reflection never touches the
 * container's own hot path.</p>
 *
 * @since 0.1.0
 */
public final class AccessorSupport {

    private AccessorSupport() {
    }

    /**
     * Resolves and opens a field for writing.
     *
     * @param type the declaring class
     * @param name the field name
     * @return the accessible field
     * @throws ExceptionInInitializerError if the field does not exist
     */
    public static Field field(Class<?> type, String name) {
        try {
            Field field = type.getDeclaredField(name);
            field.setAccessible(true);
            return field;
        } catch (NoSuchFieldException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    /**
     * Resolves and opens a method for invocation.
     *
     * @param type the declaring class
     * @param name the method name
     * @param parameterTypes the parameter types
     * @return the accessible method
     * @throws ExceptionInInitializerError if the method does not exist
     */
    public static Method method(Class<?> type, String name, Class<?>... parameterTypes) {
        try {
            Method method = type.getDeclaredMethod(name, parameterTypes);
            method.setAccessible(true);
            return method;
        } catch (NoSuchMethodException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    /**
     * Writes a field on an instance.
     *
     * @param field the accessible field
     * @param target the instance to update
     * @param value the value to store
     */
    public static void set(Field field, Object target, Object value) {
        try {
            field.set(target, value);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("Failed to inject field " + field.getName(), e);
        }
    }

    /**
     * Invokes a method on an instance.
     *
     * @param method the accessible method
     * @param target the instance to invoke on
     * @param arguments the method arguments
     */
    public static void invoke(Method method, Object target, Object... arguments) {
        try {
            method.invoke(target, arguments);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("Failed to invoke method " + method.getName(), e);
        } catch (InvocationTargetException e) {
            Throwable cause = e.getCause();
            if (cause instanceof RuntimeException runtime) {
                throw runtime;
            }
            if (cause instanceof Error error) {
                throw error;
            }
            throw new IllegalStateException("Failed to invoke method " + method.getName(), cause);
        }
    }
}
